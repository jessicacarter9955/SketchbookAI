import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-webgl']});
const errors=[];
const page=await browser.newPage({viewport:{width:1600,height:1060},deviceScaleFactor:1});
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle',timeout:30000});
await page.waitForFunction(()=>Boolean(window.__ARCADE_DEBUG__),{timeout:12000});
await page.waitForTimeout(900);
assert.equal(await page.locator('canvas').count(),1);
assert.equal(await page.evaluate(()=>window.__ARCADE_DEBUG__.getMode()),'hole');
await page.screenshot({path:'screenshot-blackhole.png',fullPage:true});
const bhBefore=await page.evaluate(()=>window.__ARCADE_DEBUG__.getState().currency);
await page.getByRole('button',{name:/Buy Black Hole Size/i}).click();
const bhAfter=await page.evaluate(()=>window.__ARCADE_DEBUG__.getState().currency);
assert(bhAfter<bhBefore,'Buying Black Hole Size must cost matter');
await page.getByRole('button',{name:/GRAVITY BURST/}).click();
await page.getByRole('tab',{name:/KEEP FISHING/}).click();
await page.waitForTimeout(600);
assert.equal(await page.evaluate(()=>window.__ARCADE_DEBUG__.getMode()),'fish');
await page.screenshot({path:'screenshot-fishing.png',fullPage:true});
await page.getByRole('button',{name:/Buy More Fishing Rods/i}).click();
const canvas=page.locator('#playfield');const box=await canvas.boundingBox();
await canvas.click({position:{x:box.width*.74,y:box.height*.46}});
await canvas.click({position:{x:box.width*.87,y:box.height*.62}});
const bobbers=await page.evaluate(()=>window.__ARCADE_DEBUG__.getBobbers());
assert.equal(bobbers.filter(b=>b.status!=='empty').length,2,'Two purchased rods must cast individually');
assert(await page.evaluate(()=>window.__ARCADE_DEBUG__.hookFirst()));
await page.locator('#primaryAction').click();
const fish=await page.evaluate(()=>window.__ARCADE_DEBUG__.getState());
assert.equal(fish.bag.length,0,'Selling must empty backpack');
assert(fish.total>0,'Selling must raise total earnings');
// Gameplay state asserted above; avoid an extra costly GPU screenshot during continuous rendering.
const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
mobile.on('pageerror',e=>errors.push(e.message));
await mobile.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle',timeout:30000});
await mobile.waitForFunction(()=>Boolean(window.__ARCADE_DEBUG__),{timeout:12000});
await mobile.screenshot({path:'screenshot-mobile.png',fullPage:false,timeout:15000,animations:'disabled'});
assert(await mobile.locator('canvas').isVisible());
assert.deepEqual(errors,[],`Console errors detected: ${errors.join('; ')}`);
console.log(JSON.stringify({result:'PASS',initialMoney:bhBefore,moneyAfterUpgrade:bhAfter,independentRods:2,fishSold:fish.sold,mobile:true,browserErrors:errors},null,2));
await browser.close();