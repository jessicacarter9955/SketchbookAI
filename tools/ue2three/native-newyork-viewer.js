import * as THREE from 'three';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {OrbitControls} from 'three/addons/controls/OrbitControls.js';

const ROOT='build/local-scenes/ue2three-districts/';
const status=document.getElementById('status');
const info=document.getElementById('info');
window.__unrealNativeViewer={ready:false,error:null};
const world=new THREE.Scene();world.background=new THREE.Color('#8298a3');
world.fog=new THREE.Fog('#8298a3',100,200);
const camera=new THREE.PerspectiveCamera(39,innerWidth/innerHeight,.02,500);
const renderer=new THREE.WebGLRenderer({antialias:true,alpha:false,powerPreference:'high-performance'});
renderer.setSize(innerWidth,innerHeight);renderer.setPixelRatio(Math.min(devicePixelRatio||1,1.75));
renderer.outputColorSpace=THREE.SRGBColorSpace;
renderer.toneMapping=THREE.ACESFilmicToneMapping;renderer.toneMappingExposure=.86;
renderer.shadowMap.enabled=true;renderer.shadowMap.type=THREE.PCFSoftShadowMap;
document.getElementById('view').append(renderer.domElement);
const controls=new OrbitControls(camera,renderer.domElement);
controls.enableDamping=true;controls.minDistance=1;controls.maxDistance=65;
world.add(new THREE.HemisphereLight(0xf1f9ff,0x334856,1.2));
const sun=new THREE.DirectionalLight(0xffe6bd,2.0);sun.position.set(-12,22,16);
sun.castShadow=true;sun.shadow.mapSize.set(1024,1024);sun.shadow.camera.left=-20;sun.shadow.camera.right=20;
sun.shadow.camera.top=20;sun.shadow.camera.bottom=-20;world.add(sun);
const fill=new THREE.DirectionalLight(0xa9d7ff,.4);fill.position.set(9,10,-10);world.add(fill);
const floor=new THREE.Mesh(new THREE.PlaneGeometry(90,90),new THREE.MeshStandardMaterial({color:0x555d61,roughness:.96}));
floor.rotation.x=-Math.PI/2;floor.position.y=-.035;floor.receiveShadow=true;world.add(floor);
const grid=new THREE.GridHelper(90,90,0x8799a7,0x7b898f);
grid.position.y=.006;grid.material.transparent=true;grid.material.opacity=.14;world.add(grid);
const resizing=()=>{camera.aspect=innerWidth/innerHeight;camera.updateProjectionMatrix();renderer.setSize(innerWidth,innerHeight);};addEventListener('resize',resizing);
(async()=>{
 const response=await fetch(ROOT+'native-meshes.json',{cache:'no-cache'});
 if(!response.ok)throw Error('Manifest degli asset Unreal non disponibile: HTTP '+response.status);
 const manifest=await response.json();
 if(manifest.source_type!=='UNREAL_NATIVE_STATIC_MESH_COMPOSITION'||manifest.full_unreal_level!==false||manifest.parts.length<5)throw Error('Provenienza UAsset non verificata');
 const gltf=await new GLTFLoader().loadAsync(ROOT+manifest.mesh);
 const model=gltf.scene;let meshes=0,textured=0,triangles=0;
 model.traverse(x=>{if(x.isMesh){meshes++;x.castShadow=true;x.receiveShadow=true;triangles+=x.geometry.index?x.geometry.index.count/3:x.geometry.attributes.position.count/3;
    if([].concat(x.material).some(y=>y.map))textured++;}});
 if(meshes<5||textured<4)throw Error('Mesh native o texture CC0 mancanti');
 const bounds=new THREE.Box3().setFromObject(model);const center=bounds.getCenter(new THREE.Vector3());
 model.position.x-=center.x;model.position.z-=center.z;model.position.y-=bounds.min.y;
 world.add(model);
 const extent=bounds.getSize(new THREE.Vector3());
 const dist=Math.max(8,Math.max(extent.x,extent.z)*1.05);
 camera.position.set(dist*.55,Math.max(5,extent.y*.95),dist*.95);
 controls.target.set(0,Math.max(1.2,extent.y*.48),0);controls.update();
 info.textContent=manifest.parts.length+' mesh Unreal originali · '+Math.round(triangles).toLocaleString('it-IT')+' triangoli · '+textured+' parti PBR fotografate';
 status.textContent='🟢 GLB reale caricato e verificato nel browser';
 window.__unrealNativeViewer={ready:true,meshCount:meshes,textured,triangles,source:manifest.source_project,
    sha256:manifest.sha256,originalSource:manifest.parts.map(x=>x.uasset),fullLevel:false};
})().catch(error=>{status.className='error';status.textContent='Errore: '+error.message;window.__unrealNativeViewer.error=error.message;});
(function animate(){requestAnimationFrame(animate);controls.update();renderer.render(world,camera);})();
